import '../../domain/entities/store_entity.dart';

class StoreModel extends StoreEntity {
  const StoreModel({
    required super.id,
    required super.name,
    required super.brandName,
    required super.category,
    required super.rating,
    required super.reviewsCount,
    required super.isOpen,
    required super.floor,
    required super.unitNumber,
    required super.openingTime,
    required super.closingTime,
    required super.managerName,
    required super.wing,
    required super.visitorsCount,
    required super.activeOffersCount,
    required super.reservationsCount,
    required super.mallName,
    required super.nearestGate,
    required super.accessPoint,
    required super.walkingTime,
    required super.mapImageUrl,
    required super.crowdLevel,
    required super.currentQueueTime,
    required super.serviceElevatorsStatus,
    required super.amenities,
    required super.phoneNumber,
    required super.email,
    required super.website,
    required super.instagramUrl,
    required super.facebookUrl,
    required super.twitterUrl,
    required super.weeklyHours,
    required super.galleryUrls,
    required super.logoUrl,
    required super.bannerUrl,
    required super.lastUpdated,
  });

  factory StoreModel.fromJson(Map<String, dynamic> json) {
    return StoreModel(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
      brandName: json['brandName'] as String? ?? '',
      category: json['category'] as String? ?? '',
      rating: (json['rating'] as num? ?? 0.0).toDouble(),
      reviewsCount: json['reviewsCount'] as int? ?? 0,
      isOpen: json['isOpen'] as bool? ?? false,
      floor: json['floor'] as String? ?? '',
      unitNumber: json['unitNumber'] as String? ?? '',
      openingTime: json['openingTime'] as String? ?? '',
      closingTime: json['closingTime'] as String? ?? '',
      managerName: json['managerName'] as String? ?? '',
      wing: json['wing'] as String? ?? '',
      visitorsCount: json['visitorsCount'] as String? ?? '',
      activeOffersCount: json['activeOffersCount'] as int? ?? 0,
      reservationsCount: json['reservationsCount'] as int? ?? 0,
      mallName: json['mallName'] as String? ?? '',
      nearestGate: json['nearestGate'] as String? ?? '',
      accessPoint: json['accessPoint'] as String? ?? '',
      walkingTime: json['walkingTime'] as String? ?? '',
      mapImageUrl: json['mapImageUrl'] as String? ?? '',
      crowdLevel: json['crowdLevel'] as String? ?? '',
      currentQueueTime: json['currentQueueTime'] as String? ?? '',
      serviceElevatorsStatus: json['serviceElevatorsStatus'] as String? ?? '',
      amenities: (json['amenities'] as List<dynamic>? ?? []).map((e) => e as String).toList(),
      phoneNumber: json['phoneNumber'] as String? ?? '',
      email: json['email'] as String? ?? '',
      website: json['website'] as String? ?? '',
      instagramUrl: json['instagramUrl'] as String? ?? '',
      facebookUrl: json['facebookUrl'] as String? ?? '',
      twitterUrl: json['twitterUrl'] as String? ?? '',
      weeklyHours: Map<String, String>.from(json['weeklyHours'] as Map? ?? {}),
      galleryUrls: (json['galleryUrls'] as List<dynamic>? ?? []).map((e) => e as String).toList(),
      logoUrl: json['logoUrl'] as String? ?? '',
      bannerUrl: json['bannerUrl'] as String? ?? '',
      lastUpdated: json['lastUpdated'] as String? ?? '',
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'brandName': brandName,
      'category': category,
      'rating': rating,
      'reviewsCount': reviewsCount,
      'isOpen': isOpen,
      'floor': floor,
      'unitNumber': unitNumber,
      'openingTime': openingTime,
      'closingTime': closingTime,
      'managerName': managerName,
      'wing': wing,
      'visitorsCount': visitorsCount,
      'activeOffersCount': activeOffersCount,
      'reservationsCount': reservationsCount,
      'mallName': mallName,
      'nearestGate': nearestGate,
      'accessPoint': accessPoint,
      'walkingTime': walkingTime,
      'mapImageUrl': mapImageUrl,
      'crowdLevel': crowdLevel,
      'currentQueueTime': currentQueueTime,
      'serviceElevatorsStatus': serviceElevatorsStatus,
      'amenities': amenities,
      'phoneNumber': phoneNumber,
      'email': email,
      'website': website,
      'instagramUrl': instagramUrl,
      'facebookUrl': facebookUrl,
      'twitterUrl': twitterUrl,
      'weeklyHours': weeklyHours,
      'galleryUrls': galleryUrls,
      'logoUrl': logoUrl,
      'bannerUrl': bannerUrl,
      'lastUpdated': lastUpdated,
    };
  }
}
