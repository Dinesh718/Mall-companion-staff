import 'package:flutter_bloc/flutter_bloc.dart';
import 'dart:math';
import '../../domain/entities/create_offer_form_entity.dart';
import '../../domain/usecases/create_offer_usecase.dart';
import '../../domain/usecases/save_offer_draft_usecase.dart';
import '../../domain/usecases/validate_offer_usecase.dart';
import '../../domain/usecases/update_offer_usecase.dart';
import 'create_offer_event.dart';
import 'create_offer_state.dart';

class CreateOfferBloc extends Bloc<CreateOfferEvent, CreateOfferState> {
  final CreateOfferUseCase createOfferUseCase;
  final SaveOfferDraftUseCase saveOfferDraftUseCase;
  final ValidateOfferUseCase validateOfferUseCase;
  final UpdateOfferUseCase? updateOfferUseCase;

  CreateOfferBloc({
    required this.createOfferUseCase,
    required this.saveOfferDraftUseCase,
    required this.validateOfferUseCase,
    this.updateOfferUseCase,
  }) : super(const CreateOfferInitial()) {
    on<InitializeCreateOffer>(_onInitializeCreateOffer);
    on<TitleChanged>(_onTitleChanged);
    on<ShortDescriptionChanged>(_onShortDescriptionChanged);
    on<DescriptionChanged>(_onDescriptionChanged);
    on<CategoryChanged>(_onCategoryChanged);
    on<OfferTypeChanged>(_onOfferTypeChanged);
    on<DiscountTypeChanged>(_onDiscountTypeChanged);
    on<DiscountValueChanged>(_onDiscountValueChanged);
    on<MinPurchaseAmountChanged>(_onMinPurchaseAmountChanged);
    on<MaxDiscountAmountChanged>(_onMaxDiscountAmountChanged);
    on<CouponCodeChanged>(_onCouponCodeChanged);
    on<IsAutoGeneratedCouponChanged>(_onIsAutoGeneratedCouponChanged);
    on<StartDateChanged>(_onStartDateChanged);
    on<EndDateChanged>(_onEndDateChanged);
    on<AudienceChanged>(_onAudienceChanged);
    on<CategoriesChanged>(_onCategoriesChanged);
    on<BannerSelected>(_onBannerSelected);
    on<TermsChanged>(_onTermsChanged);
    on<StoreBranchChanged>(_onStoreBranchChanged);
    on<SaveDraftRequested>(_onSaveDraftRequested);
    on<PublishOfferRequested>(_onPublishOfferRequested);
    on<InitializeEditOffer>(_onInitializeEditOffer);
    on<UpdateOfferRequested>(_onUpdateOfferRequested);
  }

  void _onInitializeCreateOffer(InitializeCreateOffer event, Emitter<CreateOfferState> emit) {
    final now = DateTime.now();
    final initialForm = CreateOfferFormEntity(
      startDate: now,
      endDate: now.add(const Duration(days: 7)),
      applicableCategories: const ['Fashion'],
      termsAndConditions: const [
        'Offer valid only at selected branch.',
        'Cannot be combined with other ongoing promotions.',
        'Must present coupon code at checkout.'
      ],
    );
    emit(CreateOfferEditing(initialForm));
  }

  void _onTitleChanged(TitleChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        title: event.title,
        validationErrors: Map.from(current.validationErrors)..remove('title'),
      )));
    }
  }

  void _onShortDescriptionChanged(ShortDescriptionChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        shortDescription: event.shortDescription,
      )));
    }
  }

  void _onDescriptionChanged(DescriptionChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        description: event.description,
      )));
    }
  }

  void _onCategoryChanged(CategoryChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        category: event.category,
        validationErrors: Map.from(current.validationErrors)..remove('category'),
      )));
    }
  }

  void _onOfferTypeChanged(OfferTypeChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        offerType: event.offerType,
      )));
    }
  }

  void _onDiscountTypeChanged(DiscountTypeChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        discountType: event.discountType,
      )));
    }
  }

  void _onDiscountValueChanged(DiscountValueChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        discountValue: event.discountValue,
        validationErrors: Map.from(current.validationErrors)..remove('discountValue'),
      )));
    }
  }

  void _onMinPurchaseAmountChanged(MinPurchaseAmountChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        minimumPurchaseAmount: event.minPurchaseAmount,
      )));
    }
  }

  void _onMaxDiscountAmountChanged(MaxDiscountAmountChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        maximumDiscountAmount: event.maxDiscountAmount,
      )));
    }
  }

  void _onCouponCodeChanged(CouponCodeChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        couponCode: event.couponCode,
        validationErrors: Map.from(current.validationErrors)..remove('couponCode'),
      )));
    }
  }

  void _onIsAutoGeneratedCouponChanged(IsAutoGeneratedCouponChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        isAutoGeneratedCoupon: event.isAutoGenerated,
        validationErrors: Map.from(current.validationErrors)..remove('couponCode'),
      )));
    }
  }

  void _onStartDateChanged(StartDateChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        startDate: event.startDate,
        validationErrors: Map.from(current.validationErrors)..remove('startDate'),
      )));
    }
  }

  void _onEndDateChanged(EndDateChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        endDate: event.endDate,
        validationErrors: Map.from(current.validationErrors)..remove('endDate'),
      )));
    }
  }

  void _onAudienceChanged(AudienceChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        audience: event.audience,
      )));
    }
  }

  void _onCategoriesChanged(CategoriesChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        applicableCategories: event.categories,
      )));
    }
  }

  void _onBannerSelected(BannerSelected event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        bannerUrl: event.bannerUrl,
      )));
    }
  }

  void _onTermsChanged(TermsChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        termsAndConditions: event.terms,
      )));
    }
  }

  void _onStoreBranchChanged(StoreBranchChanged event, Emitter<CreateOfferState> emit) {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferEditing(current.copyWith(
        storeBranch: event.storeBranch,
        storeId: event.storeBranch.toLowerCase().contains('concept') ? 'nike_concept' : 'nike_flagship',
      )));
    }
  }

  Future<void> _onSaveDraftRequested(SaveDraftRequested event, Emitter<CreateOfferState> emit) async {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferPublishing(current)); // saving loading state
      try {
        final randomId = 'draft_${Random().nextInt(100000)}';
        final offer = current.toEntity(id: randomId, status: 'Draft');
        final saved = await saveOfferDraftUseCase(offer);
        emit(CreateOfferDraftSaved(saved));
      } catch (e) {
        emit(CreateOfferFailure(e.toString(), current));
      }
    }
  }

  Future<void> _onPublishOfferRequested(PublishOfferRequested event, Emitter<CreateOfferState> emit) async {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferValidating(current));
      
      // Perform validation
      final validatedForm = await validateOfferUseCase(current);
      
      if (!validatedForm.isValid) {
        emit(CreateOfferValidationError(validatedForm));
        return;
      }

      emit(CreateOfferPublishing(validatedForm));
      try {
        final randomId = 'active_${Random().nextInt(100000)}';
        final offer = validatedForm.toEntity(id: randomId, status: 'Active');
        final published = await createOfferUseCase(offer);
        emit(CreateOfferPublished(published));
      } catch (e) {
        emit(CreateOfferFailure(e.toString(), validatedForm));
      }
    }
  }

  void _onInitializeEditOffer(InitializeEditOffer event, Emitter<CreateOfferState> emit) {
    final form = CreateOfferFormEntity.fromEntity(event.offer);
    emit(CreateOfferEditing(form));
  }

  Future<void> _onUpdateOfferRequested(UpdateOfferRequested event, Emitter<CreateOfferState> emit) async {
    final current = _getFormState();
    if (current != null) {
      emit(CreateOfferValidating(current));

      // Perform validation
      final validatedForm = await validateOfferUseCase(current);

      if (!validatedForm.isValid) {
        emit(CreateOfferValidationError(validatedForm));
        return;
      }

      emit(CreateOfferPublishing(validatedForm));
      try {
        final offer = validatedForm.toEntity(id: event.originalId, status: 'Active');
        if (updateOfferUseCase != null) {
          final updated = await updateOfferUseCase!(offer);
          emit(CreateOfferUpdated(updated));
        } else {
          emit(CreateOfferUpdated(offer));
        }
      } catch (e) {
        emit(CreateOfferFailure(e.toString(), validatedForm));
      }
    }
  }

  CreateOfferFormEntity? _getFormState() {
    final s = state;
    if (s is CreateOfferEditing) return s.formState;
    if (s is CreateOfferValidationError) return s.formState;
    if (s is CreateOfferFailure) return s.formState;
    if (s is CreateOfferValidating) return s.formState;
    if (s is CreateOfferPublishing) return s.formState;
    return null;
  }
}
