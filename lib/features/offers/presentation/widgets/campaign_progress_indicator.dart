import 'package:flutter/material.dart';
import '../../../../core/themes/app_colors.dart';
import '../../domain/entities/create_offer_form_entity.dart';

class CampaignProgressIndicator extends StatelessWidget {
  final CreateOfferFormEntity form;

  const CampaignProgressIndicator({
    super.key,
    required this.form,
  });

  @override
  Widget build(BuildContext context) {
    int completedSections = 0;
    if (form.title.trim().isNotEmpty) completedSections++;
    if (form.description.trim().isNotEmpty) completedSections++;
    if (form.discountValue > 0) completedSections++;
    if (form.startDate != null && form.endDate != null) completedSections++;
    if (form.couponCode.trim().isNotEmpty || form.isAutoGeneratedCoupon) completedSections++;
    if (form.applicableCategories.isNotEmpty) completedSections++;
    if (form.bannerUrl.isNotEmpty) completedSections++;
    if (form.termsAndConditions.isNotEmpty) completedSections++;

    // Clamp between 1 and 8
    completedSections = completedSections.clamp(1, 8);
    final double progress = completedSections / 8.0;

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 16.0, vertical: 8.0),
      decoration: BoxDecoration(
        color: const Color(0xFFF8F9FC),
        border: Border(
          bottom: BorderSide(
            color: AppColors.outlineVariant.withOpacity(0.3),
            width: 1.0,
          ),
        ),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              const Text(
                'Campaign Setup Progress',
                style: TextStyle(
                  fontFamily: 'Inter',
                  fontSize: 12.0,
                  fontWeight: FontWeight.bold,
                  color: AppColors.onSurfaceVariant,
                ),
              ),
              Text(
                '$completedSections of 8 sections completed',
                style: const TextStyle(
                  fontFamily: 'Inter',
                  fontSize: 12.0,
                  fontWeight: FontWeight.bold,
                  color: AppColors.primary,
                ),
              ),
            ],
          ),
          const SizedBox(height: 6.0),
          // Progress bar
          Container(
            height: 6.0,
            decoration: BoxDecoration(
              color: const Color(0xFFE5E7EB),
              borderRadius: BorderRadius.circular(99.0),
            ),
            clipBehavior: Clip.antiAlias,
            child: FractionallySizedBox(
              alignment: Alignment.centerLeft,
              widthFactor: progress,
              child: Container(
                decoration: BoxDecoration(
                  gradient: const LinearGradient(
                    colors: [
                      AppColors.primaryGradientStart,
                      AppColors.primaryGradientEnd,
                    ],
                  ),
                  borderRadius: BorderRadius.circular(99.0),
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}
