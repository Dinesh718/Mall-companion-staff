import '../entities/create_offer_form_entity.dart';
import '../repositories/offer_repository.dart';

class ValidateOfferUseCase {
  final OfferRepository repository;

  ValidateOfferUseCase(this.repository);

  Future<CreateOfferFormEntity> call(CreateOfferFormEntity form) async {
    final Map<String, String> errors = {};

    // 1. Title Validation
    if (form.title.trim().isEmpty) {
      errors['title'] = 'Campaign title is required';
    } else if (form.title.trim().length < 3) {
      errors['title'] = 'Title must be at least 3 characters long';
    }

    // 2. Category Validation
    if (form.category.trim().isEmpty) {
      errors['category'] = 'Category selection is required';
    }

    // 3. Discount Details Validation
    if (form.discountValue <= 0) {
      errors['discountValue'] = 'Discount value must be greater than zero';
    } else if (form.discountType.toLowerCase() == 'percentage' && form.discountValue > 100) {
      errors['discountValue'] = 'Percentage discount cannot exceed 100%';
    }

    if (form.minimumPurchaseAmount < 0) {
      errors['minimumPurchaseAmount'] = 'Minimum purchase amount cannot be negative';
    }

    // 4. Coupon Code Validation
    if (!form.isAutoGeneratedCoupon) {
      if (form.couponCode.trim().isEmpty) {
        errors['couponCode'] = 'Coupon code is required when auto-gen is off';
      } else if (form.couponCode.trim().length < 3) {
        errors['couponCode'] = 'Coupon code must be at least 3 characters long';
      }
    }

    // 5. Campaign Schedule Validation
    final start = form.startDate;
    final end = form.endDate;
    if (start == null) {
      errors['startDate'] = 'Start date and time are required';
    }
    if (end == null) {
      errors['endDate'] = 'End date and time are required';
    }
    if (start != null && end != null && end.isBefore(start)) {
      errors['endDate'] = 'End date cannot be before start date';
    }

    // Combine with repository-driven validation errors
    final repoErrors = await repository.validateOffer(form);
    errors.addAll(repoErrors);

    return form.copyWith(validationErrors: errors);
  }
}
