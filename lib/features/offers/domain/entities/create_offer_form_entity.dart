    this.termsAndConditions = const [],
    this.storeId = 'nike_flagship',
    this.storeBranch = 'Nike Flagship Store - Floor 2',
    this.validationErrors = const {},
  });

  factory CreateOfferFormEntity.fromEntity(OfferEntity offer) {
    String capFirst(String s) {
      if (s.isEmpty) return s;
      return s[0].toUpperCase() + s.substring(1).toLowerCase();
    }

    String mappedDType = capFirst(offer.discountType);
    if (mappedDType.toLowerCase() == 'percentage') {
      mappedDType = 'Percentage';
    } else if (mappedDType.toLowerCase() == 'flat' || mappedDType.toLowerCase() == 'flat off') {
      mappedDType = 'Flat Off';
    }

    final branch = offer.storeId.toLowerCase().contains('concept')
        ? 'Nike Concept - Floor 1'
        : 'Nike Flagship Store - Floor 2';

    // Map Category safely to dropdown options
    String mappedCategory = offer.category;
    if (mappedCategory == 'Fashion & Footwear' || mappedCategory == 'Fashion' || mappedCategory.toLowerCase().contains('apparel')) {
      mappedCategory = 'Fashion & Apparel';
    } else if (mappedCategory.toLowerCase().contains('footwear') || mappedCategory.toLowerCase().contains('shoes')) {
      mappedCategory = 'Footwear';
    } else if (mappedCategory.toLowerCase().contains('sports') || mappedCategory.toLowerCase().contains('active')) {
      mappedCategory = 'Sports';
    }
    final validCategories = ['Fashion & Apparel', 'Footwear', 'Sports'];
    if (!validCategories.contains(mappedCategory)) {
      mappedCategory = 'Fashion & Apparel';
    }

    // Map Offer Type safely to dropdown options
    String mappedOfferType = offer.offerType ?? 'Seasonal Sale';
    final validOfferTypes = ['Seasonal Sale', 'Flash Sale', 'New Collection'];
    if (!validOfferTypes.contains(mappedOfferType)) {
      if (mappedOfferType.toLowerCase().contains('flash')) {
        mappedOfferType = 'Flash Sale';
      } else if (mappedOfferType.toLowerCase().contains('new') || mappedOfferType.toLowerCase().contains('collection')) {
        mappedOfferType = 'New Collection';
      } else {
        mappedOfferType = 'Seasonal Sale';
      }
    }

    return CreateOfferFormEntity(
      title: offer.title,
      shortDescription: offer.shortDescription ?? '',
      description: offer.description,
      category: mappedCategory,
      offerType: mappedOfferType,
      discountType: mappedDType,
      discountValue: offer.discountValue,
      minimumPurchaseAmount: offer.minimumPurchaseAmount ?? 0.0,
      maximumDiscountAmount: offer.maximumDiscountAmount ?? 0.0,
      couponCode: offer.couponCode,
      isAutoGeneratedCoupon: offer.isAutoGeneratedCoupon ?? false,
      startDate: offer.startDate,
      endDate: offer.endDate,
      audience: offer.audience ?? 'All Visitors',
      applicableCategories: offer.applicableCategories ?? const ['Fashion'],
      bannerUrl: offer.bannerUrl,
      termsAndConditions: offer.termsAndConditions ?? const [],
      storeId: offer.storeId,
      storeBranch: branch,
      validationErrors: const {},
    );
  }

  bool get isValid => validationErrors.isEmpty;

