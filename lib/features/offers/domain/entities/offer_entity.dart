class OfferEntity {
  final String id;
  final String storeId;
  final String storeName;
  final String storeLogoUrl;
  final String title;
  final String description;
  final String bannerUrl;
  final String category;
  final String discountType;
  final double discountValue;
  final String couponCode;
  final String status; // "Active", "Scheduled", "Draft", "Expired"
  final DateTime startDate;
  final DateTime endDate;
  final int views;
  final int redemptions;
  final DateTime createdAt;
  final DateTime updatedAt;
  final Map<String, dynamic>? metadata;

  // Extended Details Fields
  final String? createdBy;
  final List<String>? termsAndConditions;
  final double? conversionRate;
  final String? bestPerformingDay;
  final String? peakHour;
  final String? storeLocation;
  final String? storeManagerName;
  final int? todayRedemptions;
  final int? todayViews;
  final String? campaignHealth;
  final String? campaignHealthDesc;
  final List<Map<String, dynamic>>? timeline;
  final List<Map<String, dynamic>>? systemLogs;

  // Phase 3.3 Create Offer Extended Fields
  final String? shortDescription;
  final String? offerType;
  final double? minimumPurchaseAmount;
  final double? maximumDiscountAmount;
  final bool? isAutoGeneratedCoupon;
  final String? audience;
  final List<String>? applicableCategories;

  const OfferEntity({
    required this.id,
    required this.storeId,
    required this.storeName,
    required this.storeLogoUrl,
    required this.title,
    required this.description,
    required this.bannerUrl,
    required this.category,
    required this.discountType,
    required this.discountValue,
    required this.couponCode,
    required this.status,
    required this.startDate,
    required this.endDate,
    required this.views,
    required this.redemptions,
    required this.createdAt,
    required this.updatedAt,
    this.metadata,
    this.createdBy,
    this.termsAndConditions,
    this.conversionRate,
    this.bestPerformingDay,
    this.peakHour,
    this.storeLocation,
    this.storeManagerName,
    this.todayRedemptions,
    this.todayViews,
    this.campaignHealth,
    this.campaignHealthDesc,
    this.timeline,
    this.systemLogs,
    this.shortDescription,
    this.offerType,
    this.minimumPurchaseAmount,
    this.maximumDiscountAmount,
    this.isAutoGeneratedCoupon,
    this.audience,
    this.applicableCategories,
  });
}
