import '../../domain/entities/offer_entity.dart';

class OfferModel extends OfferEntity {
  const OfferModel({
    required super.id,
    required super.storeId,
    required super.storeName,
    required super.storeLogoUrl,
    required super.title,
    required super.description,
    required super.bannerUrl,
    required super.category,
    required super.discountType,
    required super.discountValue,
    required super.couponCode,
    required super.status,
    required super.startDate,
    required super.endDate,
    required super.views,
    required super.redemptions,
    required super.createdAt,
    required super.updatedAt,
    super.metadata,
    super.createdBy,
    super.termsAndConditions,
    super.conversionRate,
    super.bestPerformingDay,
    super.peakHour,
    super.storeLocation,
    super.storeManagerName,
    super.todayRedemptions,
    super.todayViews,
    super.campaignHealth,
    super.campaignHealthDesc,
    super.timeline,
    super.systemLogs,
    super.shortDescription,
    super.offerType,
    super.minimumPurchaseAmount,
    super.maximumDiscountAmount,
    super.isAutoGeneratedCoupon,
    super.audience,
    super.applicableCategories,
  });

  factory OfferModel.fromJson(Map<String, dynamic> json) {
    return OfferModel(
      id: json['id'] as String,
      storeId: json['storeId'] as String,
      storeName: json['storeName'] as String,
      storeLogoUrl: json['storeLogoUrl'] as String,
      title: json['title'] as String,
      description: json['description'] as String,
      bannerUrl: json['bannerUrl'] as String,
      category: json['category'] as String,
      discountType: json['discountType'] as String,
      discountValue: (json['discountValue'] as num).toDouble(),
      couponCode: json['couponCode'] as String,
      status: json['status'] as String,
      startDate: DateTime.parse(json['startDate'] as String),
      endDate: DateTime.parse(json['endDate'] as String),
      views: json['views'] as int,
      redemptions: json['redemptions'] as int,
      createdAt: DateTime.parse(json['createdAt'] as String),
      updatedAt: DateTime.parse(json['updatedAt'] as String),
      metadata: json['metadata'] as Map<String, dynamic>?,
      createdBy: json['createdBy'] as String?,
      termsAndConditions: (json['termsAndConditions'] as List<dynamic>?)
          ?.map((e) => e as String)
          .toList(),
      conversionRate: (json['conversionRate'] as num?)?.toDouble(),
      bestPerformingDay: json['bestPerformingDay'] as String?,
      peakHour: json['peakHour'] as String?,
      storeLocation: json['storeLocation'] as String?,
      storeManagerName: json['storeManagerName'] as String?,
      todayRedemptions: json['todayRedemptions'] as int?,
      todayViews: json['todayViews'] as int?,
      campaignHealth: json['campaignHealth'] as String?,
      campaignHealthDesc: json['campaignHealthDesc'] as String?,
      timeline: (json['timeline'] as List<dynamic>?)
          ?.map((e) => e as Map<String, dynamic>)
          .toList(),
      systemLogs: (json['systemLogs'] as List<dynamic>?)
          ?.map((e) => e as Map<String, dynamic>)
          .toList(),
      shortDescription: json['shortDescription'] as String?,
      offerType: json['offerType'] as String?,
      minimumPurchaseAmount: (json['minimumPurchaseAmount'] as num?)?.toDouble(),
      maximumDiscountAmount: (json['maximumDiscountAmount'] as num?)?.toDouble(),
      isAutoGeneratedCoupon: json['isAutoGeneratedCoupon'] as bool?,
      audience: json['audience'] as String?,
      applicableCategories: (json['applicableCategories'] as List<dynamic>?)
          ?.map((e) => e as String)
          .toList(),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'storeId': storeId,
      'storeName': storeName,
      'storeLogoUrl': storeLogoUrl,
      'title': title,
      'description': description,
      'bannerUrl': bannerUrl,
      'category': category,
      'discountType': discountType,
      'discountValue': discountValue,
      'couponCode': couponCode,
      'status': status,
      'startDate': startDate.toIso8601String(),
      'endDate': endDate.toIso8601String(),
      'views': views,
      'redemptions': redemptions,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt.toIso8601String(),
      'metadata': metadata,
      'createdBy': createdBy,
      'termsAndConditions': termsAndConditions,
      'conversionRate': conversionRate,
      'bestPerformingDay': bestPerformingDay,
      'peakHour': peakHour,
      'storeLocation': storeLocation,
      'storeManagerName': storeManagerName,
      'todayRedemptions': todayRedemptions,
      'todayViews': todayViews,
      'campaignHealth': campaignHealth,
      'campaignHealthDesc': campaignHealthDesc,
      'timeline': timeline,
      'systemLogs': systemLogs,
      'shortDescription': shortDescription,
      'offerType': offerType,
      'minimumPurchaseAmount': minimumPurchaseAmount,
      'maximumDiscountAmount': maximumDiscountAmount,
      'isAutoGeneratedCoupon': isAutoGeneratedCoupon,
      'audience': audience,
      'applicableCategories': applicableCategories,
    };
  }
}
